import type { Element } from '../elements.ts';
import type { Item } from '../items.ts';
import type { Catalog } from './types.ts';

/** A beast's part: its tier the beast's realm, its rarity the beast's bloodline. */
function part(
  id: string,
  name: string,
  pinyin: string,
  hanzi: string,
  element: Element | null,
  properties: Property[],
  text: string,
): Item {
  return {
    id,
    name,
    pinyin,
    hanzi,
    tier: 1,
    rarity: 'gray',
    upTo: 'red',
    ...(element ? { element } : {}),
    kind: 'beast-part',
    uses: { ingredient: { properties } },
    source: 'any beast, by its species',
    text,
  };
}

