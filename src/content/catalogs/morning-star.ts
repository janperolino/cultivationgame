/** A beast's part: its tier the beast's realm, its rarity the beast's bloodline. */
function part(
  id: string,
  name: string,
  pinyin: string,
  hanzi: string,
  tags: string[],
  text: string,
): Item {
  return {
    id,
    name,
    pinyin,
    hanzi,
    tier: 1,
    rarity: 'gray',
    upTo: 'red',
    kind: 'beast-part',
    uses: { ingredient: { tags } },
    source: 'any beast, by its species',
    text,
  };
}

