/** An Art's passive, written short: the cultivator's effects, then the technique's own. */
function node(
  id: string,
  name: string,
  hanzi: string,
  cost: number,
  effects: Effect[],
  own: Effect[],
  text: string,
): ArtNodeDef {
  return {
    id,
    name,
    hanzi,
    kind: 'minor',
    cost,
    requires: [],
    effects,
    ...(own.length ? { own } : {}),
    text,
  };
}
